/** A bitmap whose every row is the captured profile, so the column axis carries the signal. */
function fromProfile(values: number[], height = 1024): Bitmap {
  const width = values.length
  const data = new Uint8ClampedArray(width * height * 4)
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4
      data[i] = values[x]
      data[i + 1] = values[x]
      data[i + 2] = values[x]
      data[i + 3] = 255
    }
  }
  return { data, width, height }
}

describe('detectGrid on real generated maps', () => {
  it('reads the 25-cell ruling the model chose for the harbour', () => {
    // The background-only recipe: the model rules its own grid at whatever spacing it likes.
    expect(detectGrid(fromProfile(RULED25))?.cols).toBe(25)
  })

  it('reads the 32-cell ruling on the tavern interior', () => {
    expect(detectGrid(fromProfile(RULED32))?.cols).toBe(32)
  })

  it('refuses a location background, which is a picture and not a map', () => {
    expect(detectGrid(fromProfile(BACKGROUND))).toBeNull()
  })

  it('reports a confidence for every map it accepts', () => {
    for (const values of [RULED25, RULED32]) {
      const detection = detectGrid(fromProfile(values))
      expect(detection?.confidence).toBeGreaterThan(0)
      expect(detection?.confidence).toBeLessThanOrEqual(1)
    }
  })
})

describe('detectGrid geometry', () => {
  it('keeps tiles square on a non-square map', () => {
    // Same ruling, quarter the height: tile SIZE is what the ruling fixes, so the row count follows.
    const detection = detectGrid(fromProfile(RULED32, 256))
    expect(detection?.cols).toBe(32)
    expect(detection?.rows).toBe(8)
  })

  it('refuses a flat image', () => {
    const width = 1024
    const height = 1024
    expect(detectGrid({ data: new Uint8ClampedArray(width * height * 4).fill(128), width, height })).toBeNull()
  })
})
